use axum::Router;

use crate::app_state::AppState;

use super::*;

pub(crate) fn router(state: AppState) -> Router {
    Router::new()
        .route("/api/v1/health", get(|| async { Json(json!({"ok": true, "runtime": "pi-rust-yll"})) }))
        .route("/api/v1/default-cwd", post(default_cwd::create))
        .route("/api/v1/terminals", post(create_terminal))
        .route("/api/v1/terminals/{id}", get(terminal_status).post(terminal_command).delete(delete_terminal))
        .route("/api/v1/terminals/{id}/events", get(terminal_events))
        .route("/api/v1/sessions", get(sessions::list_sessions).post(sessions::create_session))
        .route("/api/v1/models", get(models))
        .route("/api/v1/models/cache/invalidate", post(invalidate_models_cache))
        .route("/api/v1/models-config", get(models::config::get).put(models::config::put))
        .route("/api/v1/models-config/catalog", get(models::catalog::get))
        .route("/api/v1/models/default", axum::routing::put(save_default_preferences))
        .route("/api/v1/models/enabled-settings", get(get_enabled_model_settings).put(put_enabled_model_settings))
        .route("/api/v1/models/enabled", get(models::enabled::get).put(models::enabled::put))
        .route("/api/v1/settings/tools", get(tool_settings::get).put(tool_settings::put))
        .route("/api/v1/settings/cache-miss-notices", get(tool_settings::cache_get).put(tool_settings::cache_put))
        .route("/api/v1/prompts", get(prompts::get).put(prompts::put).delete(prompts::delete))
        .route("/api/v1/subagents/settings", get(subagent_settings::get).put(subagent_settings::put))
        .route(
            "/api/v1/subagents/profiles",
            get(subagent_profiles::list)
                .put(subagent_profiles::save)
                .patch(subagent_profiles::patch)
                .delete(subagent_profiles::delete),
        )
        .route("/api/v1/project-trust", get(project_trust::get).post(project_trust::post))
        .route("/api/v1/project-trust/fresh-check", post(project_trust::fresh_check))
        .route("/api/v1/models/refresh", post(refresh_models))
        .route("/api/v1/models-config/test", post(test_model))
        .route("/api/v1/models-config/discover", post(discover_models))
        .route("/api/v1/mcp/test", post(mcp::test::test_mcp_server))
        .route("/api/v1/mcp/config/edit", post(mcp::config_edit::edit))
        .route("/api/v1/mcp/config/sources", get(mcp::config_read::sources))
        .route("/api/v1/mcp/overview", get(mcp::config_read::overview))
        .route("/api/v1/mcp/config/auth-status", post(mcp::config_read::auth_status))
        .route("/api/v1/mcp/actions", post(mcp::actions::action))
        .route("/api/v1/mcp/ui-state/status/record", post(mcp::ui_state::record_status))
        .route("/api/v1/mcp/ui-state/status/query", post(mcp::ui_state::query_status))
        .route("/api/v1/mcp/ui-state/status/forget-entry", post(mcp::ui_state::forget_status_entry))
        .route("/api/v1/mcp/ui-state/config-key", post(mcp::ui_state::get_config_key))
        .route("/api/v1/mcp/ui-state/undo/remove", post(mcp::ui_state::remove_with_undo))
        .route("/api/v1/mcp/ui-state/undo/restore", post(mcp::ui_state::restore_undo))
        .route("/api/v1/mcp/validate", post(mcp::test::validate_mcp_server))
        .route("/api/v1/mcp/sign-out", post(mcp::test::sign_out_mcp_server))
        .route("/api/v1/mcp/sign-in", post(mcp::test::start_mcp_sign_in))
        .route("/api/v1/mcp/sign-in/{id}", get(mcp::test::get_mcp_sign_in).delete(mcp::test::cancel_mcp_sign_in))
        .route("/api/v1/mcp/sign-in/{id}/redirect", post(mcp::test::redirect_mcp_sign_in))
        .route("/api/v1/skills", get(list_skills).patch(toggle_skills))
        .route("/api/v1/skills/content", get(skill_content))
        .route("/api/v1/skills/install", post(install_skill))
        .route("/api/v1/skills/check", post(check_skills))
        .route("/api/v1/skills/search", post(search_skills))
        .route("/api/v1/skills/update", post(update_skill))
        .route("/api/v1/web-auth", get(web_auth::status).post(web_auth::login).delete(web_auth::logout))
        .route("/api/v1/web-auth/gate", get(web_auth::gate))
        .route("/api/v1/plugins/action", post(plugin_action))
        .route("/api/v1/plugins/toggle", post(plugin_toggle))
        .route("/api/v1/plugins", get(plugin_inventory))
        .route("/api/v1/plugins/check", post(check_plugin_updates))
        .route("/api/v1/provider-usage/query", post(provider_usage))
        .route("/api/v1/home", get(cwd::home))
        .route("/api/v1/app-update", get(app_update::get))
        .route("/api/v1/cwd/validate", post(cwd::validate))
        .route("/api/v1/cwd/browse", get(cwd::browse_get).post(cwd::browse_post))
        .route("/api/v1/cwd/allowed-roots", get(cwd::allowed_roots))
        .route("/api/v1/git/status", get(git_changes::status))
        .route("/api/v1/git/diff", get(git_changes::diff))
        .route("/api/v1/file-index", get(file_index::get))
        .route(
            "/api/v1/files/{*path}",
            get(workspace_files::get)
                .post(workspace_files::post)
                .layer(axum::extract::DefaultBodyLimit::max(workspace_files::MAX_UPLOAD_REQUEST_BYTES)),
        )
        .route("/api/v1/push/config", get(push::config))
        .route("/api/v1/push/subscribe", post(push::subscribe))
        .route("/api/v1/worktrees", get(worktrees::get).post(worktrees::post).delete(worktrees::delete))
        .route("/api/v1/open-in-explorer", get(open_in_explorer::get).post(open_in_explorer::post))
        .route("/api/v1/codemode/status", get(codemode_status))
        .route("/api/v1/auth/providers", get(provider_auth::auth_providers))
        .route("/api/v1/auth/api-key/{provider}", post(provider_auth::api_key_auth))
        .route("/api/v1/auth/credentials/{provider}/{expected}", post(provider_auth::delete_provider_credential))
        .route(
            "/api/v1/auth/login/{provider}",
            get(provider_auth::oauth_login).post(provider_auth::oauth_login_callback),
        )
        .route("/api/v1/sessions/running", get(sessions::running_sessions))
        .route("/api/v1/sessions/ui-state", get(session_ui_state::get).post(session_ui_state::post))
        .route("/api/v1/debug", get(sessions::debug_snapshot))
        .route("/api/v1/sessions/delete", post(sessions::delete_sessions))
        .route("/api/v1/sessions/stats", post(sessions::session_stats))
        .route("/api/v1/sessions/cwd-state", get(sessions::session_cwd_state))
        .route("/api/v1/sessions/cwd-dispose", post(sessions::dispose_sessions_for_cwd))
        .route("/api/v1/sessions/search", get(sessions::search_sessions))
        .route("/api/v1/sessions/{id}/export", get(sessions::export_session_html))
        .route("/api/v1/sessions/{id}/context", get(sessions::session_context))
        .route("/api/v1/sessions/{id}/file-reference", get(sessions::session_file_reference_route))
        .route("/api/v1/agent/{id}/bash-output", get(bash_output::get))
        .route("/api/v1/sessions/{id}/detail", get(sessions::session_detail_snapshot))
        .route("/api/v1/sessions/{id}/auto-name", post(sessions::auto_name_session))
        .route("/api/v1/sessions/{id}", get(sessions::status).delete(sessions::delete_session))
        .route("/api/v1/sessions/{id}/state", get(sessions::session_state_route))
        .route("/api/v1/sessions/{id}/rename", post(sessions::rename_session))
        .route("/api/v1/sessions/{id}/fork", post(sessions::fork_session_file))
        .route("/api/v1/sessions/{id}/entries/{entry_id}/thinking", get(sessions::session_entry_thinking))
        .route(
            "/api/v1/sessions/{id}/entries/{entry_id}/tool-result-image",
            get(sessions::session_entry_tool_result_image),
        )
        .route("/api/v1/sessions/{id}/commands", post(sessions::command))
        .route("/api/v1/sessions/{id}/lease", post(sessions::lease))
        .route("/api/v1/sessions/{id}/events", get(sessions::events))
        .merge(api_compat::router())
        .fallback(crate::static_files::serve)
        .layer(middleware::from_fn(web_auth::require_auth))
        .layer(middleware::from_fn(cors))
        .with_state(state)
}
